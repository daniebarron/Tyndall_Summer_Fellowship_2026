"""
generate_nmr_inputs.py
======================
Generates ORCA NMR input files for all 68 PFAS molecules using their
already-optimised geometries from the pfas_out_files folder.

Targets:
    - 19F NMR (primary - most sensitive to PFAS chain length and environment)
    - 1H NMR (for fluorotelomer/sulfonamide compounds with H atoms)
    - 13C NMR (optional, add to NMR_NUCLEI if wanted)

Level of theory: PBE0/def2-TZVP GIAO
    - def2-TZVP is the standard for NMR; def2-SVP is too small for chemical shifts
    - GIAO (gauge-including atomic orbitals) is the standard gauge for NMR in ORCA
    - No frequency calculation needed - single point only, much faster than opt+freq

Usage
-----
    python generate_nmr_inputs.py

Outputs:
    nmr_inputs/
        <molecule_name>/
            <molecule_name>_nmr.inp
            submit.sh
    nmr_inputs/submit_all.sh    -- submit all jobs at once
"""

import os
import re
import glob

# PATHS

OUT_FILES_DIR = r"C:\Users\danie\Downloads\orca_work\pfas_out_files"
NMR_DIR       = r"C:\Users\danie\Downloads\orca_work\nmr_inputs"
ORCA_PATH     = "/home/Daniel.Barron/software/orca_j5sY/orca"
PARTITION     = "cpuq-tyndall"

# NMR SETTINGS

# Nuclei to calculate shifts for
NMR_NUCLEI = ["19F", "1H"]

# Memory per core in MB - NMR with def2-TZVP needs more than opt+freq
MEM_MB = 4000   # per core
N_CORES = 4
TOTAL_MEM_GB = (MEM_MB * N_CORES) // 1000  # = 16 GB

WALLTIME = "12:00:00"  

# ORCA NMR INPUT TEMPLATE

def make_nmr_inp(mol_name, charge, mult, coords_block, nuclei_str):
    """
    Generate an ORCA NMR input file.

    Key keywords:
        NMR           -- requests NMR shielding calculation
        GIAO          -- gauge-including atomic orbitals (standard)
        PBE0          -- hybrid DFT, good for NMR
        def2-TZVP     -- triple-zeta, needed for accurate chemical shifts
        def2/J        -- auxiliary basis for Coulomb fitting
        RIJCOSX       -- density fitting (speeds up HF exchange)
        NormalPrint   -- don't suppress output

    The %eprnmr block specifies which nuclei to compute shifts for.
    """
    return f"""# PFAS NMR calculation: {mol_name}
# PBE0/def2-TZVP GIAO NMR
# Generated by generate_nmr_inputs.py

! NMR PBE0 def2-TZVP def2/J RIJCOSX NormalPrint

%pal
  nprocs {N_CORES}
end

%maxcore {MEM_MB}

* xyz {charge} {mult}
{coords_block}*

"""

# SLURM SUBMIT SCRIPT TEMPLATE

def make_submit(job_name, inp_path, out_path, log_name):
    return f"""#!/bin/bash
#SBATCH --job-name={job_name}
#SBATCH --output={log_name}
#SBATCH --ntasks={N_CORES}
#SBATCH --mem={TOTAL_MEM_GB}G
#SBATCH --time={WALLTIME}
#SBATCH --partition={PARTITION}
module load openmpi/gcc/64/4.1.5
ORCA={ORCA_PATH}
$ORCA {inp_path} > {out_path}
"""

# PARSE XYZ COORDINATES FROM ORCA .out FILE

def parse_final_coords(out_filepath):
    """
    Extract the final optimised geometry from an ORCA .out file.
    ORCA prints the final geometry in a 'CARTESIAN COORDINATES (ANGSTROEM)' block
    near the end of the file. We want the LAST occurrence.

    Returns (charge, multiplicity, coords_block_str) or None on failure.
    """
    try:
        with open(out_filepath, "r", encoding="utf-8", errors="replace") as f:
            lines = f.readlines()
    except Exception as e:
        return None, None, None

    # Find charge and multiplicity from input section
    charge = 0
    mult = 1
    for line in lines:
        m = re.search(r"Total Charge\s+Charge\s+\.\.\.\.\s+(-?\d+)", line)
        if m:
            charge = int(m.group(1))
        m = re.search(r"Multiplicity\s+Mult\s+\.\.\.\.\s+(\d+)", line)
        if m:
            mult = int(m.group(1))

    # Find the LAST Cartesian coordinates block
    last_coord_start = None
    for i, line in enumerate(lines):
        if "CARTESIAN COORDINATES (ANGSTROEM)" in line:
            last_coord_start = i

    if last_coord_start is None:
        return None, None, None

    # Parse coordinates from that block
    coords = []
    i = last_coord_start + 2  # skip header and dashes line
    while i < len(lines):
        line = lines[i].strip()
        if line == "" or line.startswith("-"):
            break
        parts = line.split()
        if len(parts) == 4:
            try:
                atom = parts[0]
                x, y, z = float(parts[1]), float(parts[2]), float(parts[3])
                coords.append(f"  {atom:<4s}  {x:14.8f}  {y:14.8f}  {z:14.8f}")
            except ValueError:
                break
        i += 1

    if not coords:
        return None, None, None

    return charge, mult, "\n".join(coords) + "\n"

# MAIN

def main():
    # Handle Windows paths when run on Windows
    out_dir = OUT_FILES_DIR
    nmr_dir = NMR_DIR

    os.makedirs(nmr_dir, exist_ok=True)

    out_files = sorted(glob.glob(os.path.join(out_dir, "*.out")))
    print(f"Found {len(out_files)} .out files")

    nuclei_str = " ".join(NMR_NUCLEI)

    ok_count = 0
    failed = []
    all_submit_paths = []

    for out_filepath in out_files:
        filename = os.path.basename(out_filepath)
        # Remove .out and _freq suffix to get molecule name
        mol_name = re.sub(r"_freq$", "", filename[:-4])

        charge, mult, coords = parse_final_coords(out_filepath)

        if coords is None:
            print(f"  [FAIL] {mol_name} -- could not parse coordinates")
            failed.append(mol_name)
            continue

        # Determine nuclei - skip 1H for fully perfluorinated molecules
        # (they have no H atoms so 1H NMR would be empty)
        has_H = "H" in coords
        if not has_H:
            nuclei = "19F"
        else:
            nuclei = " ".join(NMR_NUCLEI)

        # Create molecule subdirectory
        mol_dir = os.path.join(nmr_dir, mol_name)
        os.makedirs(mol_dir, exist_ok=True)

        # Write .inp file
        inp_name = f"{mol_name}_nmr.inp"
        inp_path_local = os.path.join(mol_dir, inp_name)
        inp_content = make_nmr_inp(mol_name, charge, mult, coords, nuclei)

        with open(inp_path_local, "w", encoding="utf-8") as f:
            f.write(inp_content)

        # Write submit.sh (paths are cluster paths - adjust prefix)
        cluster_base = f"/home/Daniel.Barron/nmr_inputs/{mol_name}"
        inp_path_cluster  = f"{cluster_base}/{inp_name}"
        out_path_cluster  = f"{cluster_base}/{mol_name}_nmr.out"
        log_name          = f"{mol_name}_nmr.log"

        submit_content = make_submit(
            job_name = mol_name[:16] + "_nmr",
            inp_path = inp_path_cluster,
            out_path = out_path_cluster,
            log_name = log_name,
        )
        submit_path_local = os.path.join(mol_dir, "submit.sh")
        with open(submit_path_local, "w", encoding="utf-8", newline="\n") as f:
            f.write(submit_content)

        all_submit_paths.append(f"sbatch /home/Daniel.Barron/nmr_inputs/{mol_name}/submit.sh")
        ok_count += 1
        print(f"  [OK]  {mol_name}  (charge={charge}, mult={mult}, nuclei={nuclei})")

    # Write master submission script
    submit_all_path = os.path.join(nmr_dir, "submit_all.sh")
    with open(submit_all_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("#!/bin/bash\n# Submit all 68 NMR jobs\n# Run this from adahead\n\n")
        f.write("\n".join(all_submit_paths) + "\n")

    print(f"\nGenerated {ok_count} NMR input files in {nmr_dir}")
    if failed:
        print(f"Failed: {failed}")
    print(f"\nTo submit all jobs, copy nmr_inputs/ to the cluster and run:")
    print(f"  bash /home/Daniel.Barron/nmr_inputs/submit_all.sh")

if __name__ == "__main__":
    main()